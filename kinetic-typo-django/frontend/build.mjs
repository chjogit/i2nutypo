// Builds the editor into the Django app's static folder:
//   ../static/js/studio.js           editor (React app)
//   ../static/js/whisper-worker.js   speech recognition worker
//   ../static/js/separation-worker.js vocal separation worker
//   ../static/js/ffmpeg-worker.js    ProRes export worker
//   ../static/css/studio.css         Tailwind styles
//   ../static/licenses/THIRD_PARTY_NOTICES.txt  licences of the packages bundled above and of static/fonts/
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import tailwindcss from "@tailwindcss/postcss";
import * as esbuild from "esbuild";
import postcss from "postcss";

const watch = process.argv.includes("--watch");
const root = fileURLToPath(new URL(".", import.meta.url));
const staticDir = fileURLToPath(new URL("../static/", import.meta.url));
const cssIn = `${root}src/styles.css`;
const cssOut = `${staticDir}css/studio.css`;

/** Tailwind scans src/ for class names, so it reruns whenever the editor bundle rebuilds. */
async function buildCss() {
  const result = await postcss([tailwindcss({ base: root, optimize: !watch })]).process(
    await readFile(cssIn, "utf8"),
    {
      from: cssIn,
      to: cssOut,
    },
  );
  await writeFile(cssOut, result.css);
}

/** @type {esbuild.Plugin} */
const cssOnRebuild = {
  name: "tailwind",
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length === 0) await buildCss();
    });
  },
};

/** @type {esbuild.BuildOptions} */
const shared = {
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  minify: !watch,
  sourcemap: watch,
  logLevel: "info",
  absWorkingDir: root,
  alias: { "@": "./src" },
  // transformers.js and @audio/neural-separate run in the browser only; their Node paths are never loaded
  external: ["sharp", "onnxruntime-node", "node:*"],
  define: { "process.env.NODE_ENV": JSON.stringify(watch ? "development" : "production") },
};

const studio = {
  ...shared,
  entryPoints: { studio: "src/main.tsx" },
  outdir: `${staticDir}js`,
  plugins: [cssOnRebuild],
};
const worker = {
  ...shared,
  entryPoints: {
    "whisper-worker": "src/workers/whisper.worker.ts",
    "separation-worker": "src/workers/separation.worker.ts",
    // FFmpeg (WebAssembly) runs here for ProRes export; the program itself is fetched when first used
    "ffmpeg-worker": "node_modules/@ffmpeg/ffmpeg/dist/esm/worker.js",
  },
  outdir: `${staticDir}js`,
};

/** The npm package a bundled file belongs to, from its path under node_modules/. */
function packageDir(file) {
  if (file.startsWith("(disabled):")) return null;
  const m = file.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  return m ? m[1] : null;
}

/**
 * Writes the licence of every package that ended up in a bundle (esbuild's metafile says which),
 * then of every font in static/fonts/, so the notices always match what is shipped.
 */
async function writeNotices(results) {
  const dirs = new Set();
  for (const r of results) for (const file of Object.keys(r.metafile.inputs)) {
    const dir = packageDir(file);
    if (dir) dirs.add(dir);
  }
  const parts = [
    "Third-party notices for Kinetic Typo Studio",
    "Generated by frontend/build.mjs from the files bundled into static/js and the fonts in static/fonts.",
    "",
  ];
  const packages = [];
  for (const dir of dirs) {
    const pkg = JSON.parse(await readFile(`${root}${dir}/package.json`, "utf8"));
    const licenceFile = (await readdir(`${root}${dir}`)).find((f) => /^(licen[cs]e|copying)/i.test(f));
    const notice = existsSync(`${root}${dir}/NOTICE`) ? await readFile(`${root}${dir}/NOTICE`, "utf8") : "";
    const text = licenceFile ? await readFile(`${root}${dir}/${licenceFile}`, "utf8") : "";
    packages.push({ name: pkg.name, version: pkg.version, license: pkg.license ?? "see package", text, notice });
  }
  packages.sort((a, b) => a.name.localeCompare(b.name));
  for (const p of packages) {
    parts.push("=".repeat(72), `${p.name} ${p.version} (${p.license})`, "=".repeat(72));
    if (p.text) parts.push(p.text.trim());
    else parts.push(`Licensed under ${p.license}; the package ships no separate licence file.`);
    if (p.notice) parts.push("", p.notice.trim());
    parts.push("");
  }
  const fontsDir = `${staticDir}fonts/`;
  if (existsSync(`${fontsDir}fonts.json`)) {
    const fonts = JSON.parse(await readFile(`${fontsDir}fonts.json`, "utf8"));
    for (const f of fonts) {
      parts.push("=".repeat(72), `Font: ${f.family} (${f.license}), via Fontsource ${f.version}`, "=".repeat(72));
      if (existsSync(`${fontsDir}${f.slug}/LICENSE`)) parts.push((await readFile(`${fontsDir}${f.slug}/LICENSE`, "utf8")).trim());
      parts.push("");
    }
  }
  await mkdir(`${staticDir}licenses`, { recursive: true });
  await writeFile(`${staticDir}licenses/THIRD_PARTY_NOTICES.txt`, parts.join("\n"));
  await writeFile(
    `${staticDir}licenses/packages.json`,
    `${JSON.stringify(packages.map(({ name, version, license }) => ({ name, version, license })), null, 2)}\n`,
  );
}

if (watch) {
  await (await esbuild.context(studio)).watch();
  await (await esbuild.context(worker)).watch();
} else {
  const results = await Promise.all([
    esbuild.build({ ...studio, metafile: true }),
    esbuild.build({ ...worker, metafile: true }),
  ]);
  await writeNotices(results);
}
