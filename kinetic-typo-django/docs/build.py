"""Renders docs/*.md into templates/docs/_*.html, which templates/docs.html includes.

Run after editing a .md file (needs `pip install markdown`, only for this step):

    python docs/build.py
"""
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "templates" / "docs"

for name in ("guide", "about"):
    text = (ROOT / "docs" / f"{name}.md").read_text(encoding="utf-8")
    # The page shows its own title per section, so the file's "# ..." line is dropped
    body = "\n".join(line for line in text.splitlines() if not line.startswith("# "))
    count = iter(range(1, 1000))
    # Ids like guide-1, guide-2 … so the page's table of contents can link to each "##" section
    md = markdown.Markdown(
        extensions=["tables", "toc", "sane_lists"],
        extension_configs={"toc": {"slugify": lambda value, sep, n=name: f"{n}-{next(count)}", "toc_depth": "2"}},
    )
    html = md.convert(body)
    OUT.mkdir(exist_ok=True)
    (OUT / f"_{name}.html").write_text(
        "{#- Generated by docs/build.py from docs/" + name + ".md. Edit the .md file, not this one. -#}\n" + html + "\n",
        encoding="utf-8",
    )
    print(f"templates/docs/_{name}.html")
